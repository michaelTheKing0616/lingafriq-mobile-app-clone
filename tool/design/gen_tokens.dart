import 'dart:convert';
import 'dart:io';

class TokenGenException implements Exception {
  TokenGenException(this.message);
  final String message;
  @override
  String toString() => message;
}

class GeneratedTokens {
  GeneratedTokens({
    required this.dartSource,
    required this.adminCss,
    required this.riveJson,
  });

  final String dartSource;
  final String adminCss;
  final String riveJson;
}

GeneratedTokens generateTokens(Map<String, dynamic> spec) {
  final colors = _map(spec, 'color');
  final spacing = _map(spec, 'spacing');
  final radius = _map(spec, 'radius');
  final elevation = _map(spec, 'elevation');
  final stroke = _map(spec, 'stroke');
  final light = _map(elevation, 'light');
  final dark = _map(elevation, 'dark');
  if (light.keys.toSet().difference(dark.keys.toSet()).isNotEmpty ||
      dark.keys.toSet().difference(light.keys.toSet()).isNotEmpty) {
    throw TokenGenException('elevation light and dark steps must match');
  }

  final resolved = <String, String>{};
  for (final name in colors.keys.toList()..sort()) {
    resolved[name] = _resolveColor(colors[name], colors, name);
    final binding = colors[name];
    if (binding is! Map ||
        binding['rive'] is! String ||
        (binding['rive'] as String).isEmpty) {
      throw TokenGenException('missing Rive binding for color.$name');
    }
  }

  for (final entry in spacing.entries) {
    final value = entry.value;
    if (value is! num || value % 4 != 0) {
      throw TokenGenException('spacing.${entry.key} is not a multiple of 4');
    }
  }

  final dart =
      StringBuffer(
          '// Generated by tool/design/gen_tokens.dart. Do not edit.\n',
        )
        ..writeln("import 'package:flutter/material.dart';")
        ..writeln()
        ..writeln('abstract final class LingAfriqTokens {');
  for (final name in resolved.keys) {
    final hex = resolved[name]!;
    final argb = hex.length == 8 ? hex : 'FF$hex';
    dart.writeln('  static const Color $name = Color(0x$argb);');
  }
  _writeRampRoles(dart, spec, resolved.keys.toSet());
  for (final key in spacing.keys.toList()..sort()) {
    dart.writeln('  static const double spacing$key = ${spacing[key]}.0;');
  }
  for (final key in radius.keys.toList()..sort()) {
    dart.writeln('  static const double radius$key = ${radius[key]}.0;');
  }
  for (final key in light.keys.toList()..sort()) {
    dart.writeln('  static const double elevationLight$key = ${light[key]}.0;');
    dart.writeln('  static const double elevationDark$key = ${dark[key]}.0;');
  }
  for (final key in stroke.keys.toList()..sort()) {
    dart.writeln('  static const double stroke$key = ${stroke[key]}.0;');
  }
  final motion = _motion(spec);
  dart.writeln(
    "  static const String motionProductEasing = '${motion.productEasing}';",
  );
  for (final entry in motion.productDurations.entries) {
    dart.writeln(
      '  static const int motionProduct${_pascal(entry.key)} = ${entry.value};',
    );
  }
  final typeStyles = _typeScale(spec);
  for (final style in typeStyles) {
    dart.writeln(
      "  static const String typeId${_pascal(style.name)} = '${style.token}';",
    );
    dart.writeln(
      "  static const String typeRole${_pascal(style.name)} = '${style.role}';",
    );
  }
  dart.writeln(
    "  static const String motionRareEasing = '${motion.rareEasing}';",
  );
  for (final entry in motion.rareDurations.entries) {
    dart.writeln(
      '  static const int motionRare${_pascal(entry.key)} = ${entry.value};',
    );
  }
  dart.writeln('}');

  final css = StringBuffer(':root {\n');
  for (final name in resolved.keys) {
    css.writeln('  --color-$name: #${resolved[name]};');
  }
  for (final key in spacing.keys.toList()..sort()) {
    css.writeln('  --spacing-$key: ${spacing[key]}px;');
  }
  final motionCss = _motion(spec);
  for (final style in _typeScale(spec)) {
    css.writeln('  --${style.token}: ${style.family};');
  }
  css.writeln('  --motion-product-easing: ${motionCss.productEasing};');
  for (final entry in motionCss.productDurations.entries) {
    css.writeln('  --motion-product-${entry.key}: ${entry.value}ms;');
  }
  css.writeln('  --motion-rare-easing: ${motionCss.rareEasing};');
  for (final entry in motionCss.rareDurations.entries) {
    css.writeln('  --motion-rare-${entry.key}: ${entry.value}ms;');
  }
  css.writeln('}');

  final rive = <String, String>{};
  for (final name in resolved.keys) {
    rive[(colors[name] as Map)['rive'] as String] = '#${resolved[name]}';
  }
  final riveKeys = rive.keys.toList()..sort();
  final riveOut = {for (final k in riveKeys) k: rive[k]};

  return GeneratedTokens(
    dartSource: dart.toString(),
    adminCss: css.toString(),
    riveJson: '${const JsonEncoder.withIndent('  ').convert(riveOut)}\n',
  );
}

List<String> reportPaddingLiterals(String source, String path) {
  final hits = <String>[];
  final pattern = RegExp(r'EdgeInsets(?:\.\w+)?\(\s*(\d+(?:\.\d+)?)');
  final lines = source.split('\n');
  for (var i = 0; i < lines.length; i++) {
    final match = pattern.firstMatch(lines[i]);
    if (match == null) continue;
    final value = num.parse(match.group(1)!);
    if (value % 4 != 0) {
      hits.add('$path:${i + 1}');
    }
  }
  return hits;
}

class _Motion {
  _Motion({
    required this.productEasing,
    required this.productDurations,
    required this.rareEasing,
    required this.rareDurations,
  });

  final String productEasing;
  final Map<String, int> productDurations;
  final String rareEasing;
  final Map<String, int> rareDurations;
}

const _easeOut = 'cubic-bezier(0.23,1,0.32,1)';

class _TypeStyle {
  _TypeStyle({
    required this.name,
    required this.token,
    required this.role,
    required this.family,
    required this.size,
    required this.height,
  });

  final String name;
  final String token;
  final String role;
  final String family;
  final double size;
  final double height;
}

List<_TypeStyle> _typeScale(Map<String, dynamic> spec) {
  final type = _map(spec, 'type');
  final out = <_TypeStyle>[];
  for (final name in type.keys.toList()..sort()) {
    final raw = type[name];
    if (raw is! Map) throw TokenGenException('type.$name is invalid');
    final role = raw['role'];
    final family = raw['family'];
    final size = raw['size'];
    final height = raw['height'];
    final token = raw['id'];
    if (role is! String || family is! String || token is! String) {
      throw TokenGenException('type.$name is missing role, family, or id');
    }
    if (size is! num || height is! num) {
      throw TokenGenException('type.$name is missing size or height');
    }
    if (role == 'target-language' && (size < 18 || height < 1.5)) {
      throw TokenGenException('type.$name is below the 18sp / 1.5 floor');
    }
    out.add(
      _TypeStyle(
        name: name,
        token: token,
        role: role,
        family: family,
        size: size.toDouble(),
        height: height.toDouble(),
      ),
    );
  }
  return out;
}

_Motion _motion(Map<String, dynamic> spec) {
  final motion = _map(spec, 'motion');
  final product = _map(motion, 'product');
  final rare = _map(motion, 'rare');
  if (product['easing'] != _easeOut) {
    throw TokenGenException('product easing must be $_easeOut');
  }
  final productDurations = _durations(product, 'product', 300);
  final rareDurations = _durations(rare, 'rare', null);
  final uses = rare['allowedUses'];
  if (uses is! List ||
      uses.toSet().difference({'lesson-complete', 'level-up'}).isNotEmpty) {
    throw TokenGenException(
      'rare motion is only for lesson-complete and level-up',
    );
  }
  return _Motion(
    productEasing: product['easing'] as String,
    productDurations: productDurations,
    rareEasing: rare['easing'] as String,
    rareDurations: rareDurations,
  );
}

Map<String, int> _durations(Map<String, dynamic> group, String tier, int? cap) {
  final raw = group['durationMs'];
  if (raw is! Map || raw.isEmpty) {
    throw TokenGenException('$tier motion has no durations');
  }
  final out = <String, int>{};
  for (final key in raw.keys.toList()..sort()) {
    final value = raw[key];
    if (value is! num || value < 0) {
      throw TokenGenException('$tier duration $key is invalid');
    }
    if (cap != null && value > cap) {
      throw TokenGenException('$tier duration $key is above ${cap}ms');
    }
    out[key.toString()] = value.toInt();
  }
  return out;
}

String _pascal(String key) => key[0].toUpperCase() + key.substring(1);

const _requiredRampRoles = <String>[
  'roleLightSurface',
  'roleLightOnSurface',
  'roleLightSurfaceContainer',
  'roleLightAccent',
  'roleLightOnAccent',
  'roleDarkSurface',
  'roleDarkOnSurface',
  'roleDarkSurfaceContainer',
  'roleDarkAccent',
  'roleDarkOnAccent',
];

void _writeRampRoles(
  StringBuffer dart,
  Map<String, dynamic> spec,
  Set<String> colorNames,
) {
  final root = spec['colorRamps'];
  if (root is! Map) {
    throw TokenGenException('missing colorRamps');
  }
  final rampsRoot = root.cast<String, dynamic>();
  final ramps = _map(rampsRoot, 'ramps');
  final modes = _map(rampsRoot, 'modes');
  final lines = <String, String>{};
  for (final mode in modes.keys.toList()..sort()) {
    final roles = _map(modes, mode);
    for (final role in roles.keys.toList()..sort()) {
      final binding = _map(roles, role);
      final rampName = binding['ramp'];
      final step = binding['step'];
      if (rampName is! String || step is! num) {
        throw TokenGenException('colorRamps.modes.$mode.$role is invalid');
      }
      final ramp = _map(ramps, rampName);
      final steps = _map(ramp, 'steps');
      final stepKey = '${step.toInt()}';
      final stepNode = steps[stepKey];
      if (stepNode is! Map || stepNode['hex'] is! String) {
        throw TokenGenException(
          'colorRamps.ramps.$rampName.steps.$stepKey has no hex',
        );
      }
      final hex = (stepNode['hex'] as String)
          .replaceFirst('#', '')
          .toUpperCase();
      if (!RegExp(r'^[0-9A-F]{6}([0-9A-F]{2})?$').hasMatch(hex)) {
        throw TokenGenException(
          'colorRamps.ramps.$rampName.steps.$stepKey is not hex',
        );
      }
      final argb = hex.length == 8 ? hex : 'FF$hex';
      final dartName = 'role${_pascal(mode)}${_pascal(role)}';
      if (lines.containsKey(dartName)) {
        throw TokenGenException('duplicate ramp role $dartName');
      }
      if (colorNames.contains(dartName)) {
        throw TokenGenException(
          'ramp role $dartName collides with a color token',
        );
      }
      lines[dartName] = argb;
    }
  }
  for (final name in _requiredRampRoles) {
    if (!lines.containsKey(name)) {
      throw TokenGenException('missing ramp role $name');
    }
  }
  for (final name in lines.keys.toList()..sort()) {
    dart.writeln('  static const Color $name = Color(0x${lines[name]});');
  }
}

Map<String, dynamic> _map(Map<String, dynamic> spec, String key) {
  final value = spec[key];
  if (value is! Map) {
    throw TokenGenException('missing $key');
  }
  return value.cast<String, dynamic>();
}

String _resolveColor(dynamic node, Map<String, dynamic> colors, String name) {
  if (node is! Map || node['value'] is! String) {
    throw TokenGenException('color.$name has no value');
  }
  final raw = (node['value'] as String).trim();
  if (raw.startsWith('{') && raw.endsWith('}')) {
    final ref = raw.substring(1, raw.length - 1);
    if (!ref.startsWith('color.') || !colors.containsKey(ref.substring(6))) {
      throw TokenGenException('unknown token $ref');
    }
    return _resolveColor(colors[ref.substring(6)], colors, ref.substring(6));
  }
  final hex = raw.replaceFirst('#', '').toUpperCase();
  if (!RegExp(r'^[0-9A-F]{6}([0-9A-F]{2})?$').hasMatch(hex)) {
    throw TokenGenException('color.$name is not a 6-digit or 8-digit hex');
  }
  return hex;
}

void writeGenerated(GeneratedTokens out, {Directory? root}) {
  final base = root ?? Directory.current;
  File('${base.path}/lib/design/tokens.g.dart')
    ..parent.createSync(recursive: true)
    ..writeAsStringSync(out.dartSource);
  File('${base.path}/design/tokens/admin.css')
    ..parent.createSync(recursive: true)
    ..writeAsStringSync(out.adminCss);
  File(
    '${base.path}/design/tokens/rive_tokens.json',
  ).writeAsStringSync(out.riveJson);
}

void main() {
  try {
    final spec =
        jsonDecode(File('design/tokens/tokens.json').readAsStringSync())
            as Map<String, dynamic>;
    writeGenerated(generateTokens(spec));
  } on TokenGenException catch (e) {
    stderr.writeln(e);
    exit(1);
  }
}
