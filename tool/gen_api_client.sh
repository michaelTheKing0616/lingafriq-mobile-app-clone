#!/usr/bin/env bash
# Generate the Dart API client from docs/api/openapi.v1.json.
set -euo pipefail
cd "$(dirname "$0")/.."
python3 - <<'PY'
import json
from pathlib import Path

spec_path = Path("docs/api/openapi.v1.json")
out_dir = Path("lib/api/generated")
out_dir.mkdir(parents=True, exist_ok=True)
spec = json.loads(spec_path.read_text())
version = spec["info"]["version"]
operations = []
for path, methods in spec["paths"].items():
    for method, _operation in methods.items():
        operations.append((method.upper(), path))
operations.sort()

def dart_string(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"

lines = [
    "// Generated by tool/gen_api_client.sh from docs/api/openapi.v1.json.",
    f"// Spec version {version}.",
    "",
    "import 'package:dio/dio.dart';",
    "",
    "import 'api_error.dart';",
    "",
    f"const String openApiSpecVersion = {dart_string(version)};",
    "",
    "class ApiOperation {",
    "  const ApiOperation(this.method, this.path);",
    "",
    "  final String method;",
    "  final String path;",
    "}",
    "",
    "const Map<String, ApiOperation> apiOperations = {",
]
for method, path in operations:
    key = f"{method} {path}"
    lines.append(f"  {dart_string(key)}: ApiOperation({dart_string(method)}, {dart_string(path)}),")
lines += [
    "};",
    "",
    "class LingAfriqApi {",
    "  LingAfriqApi({required this.baseUrl, Dio? dio})",
    "      : _dio = dio ?? Dio(BaseOptions(baseUrl: baseUrl));",
    "",
    "  final String baseUrl;",
    "  final Dio _dio;",
    "",
    "  Future<Response<dynamic>> send(",
    "    String operation, {",
    "    Map<String, String> pathParameters = const {},",
    "    Object? body,",
    "    Map<String, dynamic>? query,",
    "  }) async {",
    "    final spec = apiOperations[operation];",
    "    if (spec == null) {",
    "      throw ApiError(method: '', path: operation, message: 'Unknown operation');",
    "    }",
    "    var path = spec.path;",
    "    for (final entry in pathParameters.entries) {",
    "      path = path.replaceAll('{${entry.key}}', Uri.encodeComponent(entry.value));",
    "    }",
    "    try {",
    "      return await _dio.request<dynamic>(",
    "        path,",
    "        data: body,",
    "        queryParameters: query,",
    "        options: Options(method: spec.method),",
    "      );",
    "    } on DioException catch (error) {",
    "      throw ApiError(",
    "        method: spec.method,",
    "        path: path,",
    "        statusCode: error.response?.statusCode,",
    "        cause: error,",
    "      );",
    "    }",
    "  }",
    "}",
    "",
]
(out_dir / "api_client.dart").write_text("\n".join(lines))
(out_dir / "api_error.dart").write_text(
    "\n".join(
        [
            "// Generated by tool/gen_api_client.sh from docs/api/openapi.v1.json.",
            f"// Spec version {version}.",
            "",
            "class ApiError implements Exception {",
            "  ApiError({",
            "    required this.method,",
            "    required this.path,",
            "    this.statusCode,",
            "    this.message,",
            "    this.cause,",
            "  });",
            "",
            "  final String method;",
            "  final String path;",
            "  final int? statusCode;",
            "  final String? message;",
            "  final Object? cause;",
            "",
            "  @override",
            "  String toString() {",
            "    final status = statusCode == null ? '' : ' status=$statusCode';",
            "    final detail = message ?? cause?.toString() ?? 'request failed';",
            "    return 'ApiError($method $path$status): $detail';",
            "  }",
            "}",
            "",
        ]
    )
)
print(f"wrote {len(operations)} operations at version {version}")
PY
