/// One scored label from the bundled classifier (not ML Kit scene categories).
class ObjectClassificationLabel {
  const ObjectClassificationLabel({
    required this.label,
    required this.score,
  });

  final String label;
  final double score;
}

/// ML Kit coarse scene buckets — must never be returned as Point-and-Say labels.
const Set<String> mlKitSceneCategoryLabels = {
  'Food',
  'Home good',
  'Fashion good',
  'Plant',
  'Place',
};

/// Records per-frame inference latency and evaluates the 150 ms p50 bar.
class PointSayLatencyRecorder {
  PointSayLatencyRecorder({this.p50TargetMs = 150});

  final int p50TargetMs;
  final List<int> _samplesMs = [];

  void record(int elapsedMs) {
    if (elapsedMs < 0) return;
    _samplesMs.add(elapsedMs);
  }

  List<int> get samplesMs => List.unmodifiable(_samplesMs);

  int? p50Ms() {
    if (_samplesMs.isEmpty) return null;
    final sorted = List<int>.from(_samplesMs)..sort();
    return sorted[(sorted.length * 0.5).floor().clamp(0, sorted.length - 1)];
  }

  /// True only when a sample exists and p50 is at or below the target.
  bool meetsLatencyBar() {
    final p50 = p50Ms();
    if (p50 == null) return false;
    return p50 <= p50TargetMs;
  }
}

/// Thin wrapper so tests can inject a fake engine without loading TFLite.
abstract class PointSayInferenceEngine {
  void run(
    List<List<List<List<double>>>> input,
    List<List<double>> output,
  );

  void close();
}

class TflitePointSayEngine implements PointSayInferenceEngine {
  TflitePointSayEngine(Uint8List modelBytes)
      : _interpreter = Interpreter.fromBuffer(modelBytes);

  final Interpreter _interpreter;

  @override
  void run(
    List<List<List<List<double>>>> input,
    List<List<double>> output,
  ) {
    _interpreter.run(input, output);
  }

  @override
  void close() => _interpreter.close();
}

typedef PointSayEngineFactory = PointSayInferenceEngine Function(Uint8List bytes);

/// Runs MobileNetV4 on 224×224 RGB float input in [0, 1], returns top-3 ImageNet labels.
class OnDeviceObjectClassifier {
  OnDeviceObjectClassifier({
    PointSayEngineFactory? engineFactory,
    PointSayLatencyRecorder? latencyRecorder,
    Future<ByteData> Function(String asset)? loadAsset,
  })  : _engineFactory =
            engineFactory ?? ((bytes) => TflitePointSayEngine(bytes)),
        _latency = latencyRecorder ?? PointSayLatencyRecorder(),
        _loadAsset = loadAsset ?? rootBundle.load;

  final PointSayEngineFactory _engineFactory;
  final PointSayLatencyRecorder _latency;
  final Future<ByteData> Function(String asset) _loadAsset;

  PointSayInferenceEngine? _engine;
  List<String>? _labels;

  PointSayLatencyRecorder get latencyRecorder => _latency;

  Future<void> load() async {
    if (_engine != null) return;
    final bytes = await _loadAsset(PointSayModelLicence.bundledAsset);
    _engine = _engineFactory(bytes.buffer.asUint8List());
    _labels = List<String>.from(_kImageNetLabels);
  }

  Future<void> close() async {
    _engine?.close();
    _engine = null;
  }

  bool get isLoaded => _engine != null;

  /// Classifies a single 224×224 RGB frame. [rgbFloat01] length must be 224 * 224 * 3.
  Future<List<ObjectClassificationLabel>> classifyFrame(
    Float32List rgbFloat01, {
    DateTime? startedAt,
  }) async {
    await load();
    final engine = _engine!;
    final labels = _labels!;
    if (rgbFloat01.length != 224 * 224 * 3) {
      throw ArgumentError.value(
        rgbFloat01.length,
        'rgbFloat01',
        'expected 150528 floats (224x224x3)',
      );
    }

    final sw = startedAt ?? DateTime.now();
    final input = _reshapeInput(rgbFloat01);
    final output = List.generate(1, (_) => List.filled(1000, 0.0));
    engine.run(input, output);
    final elapsed = DateTime.now().difference(sw).inMilliseconds;
    _latency.record(elapsed);

    final logits = output.first;
    final ranked = _topKIndices(logits, logits.length);
    final results = <ObjectClassificationLabel>[];
    for (final i in ranked) {
      if (results.length >= 3) break;
      final label = labels[i];
      if (mlKitSceneCategoryLabels.contains(label)) continue;
      results.add(
        ObjectClassificationLabel(
          label: label,
          score: _softmaxScore(logits, i),
        ),
      );
    }
    return results;
  }

  List<List<List<List<double>>>> _reshapeInput(Float32List flat) {
    final cube = List.generate(
      1,
      (_) => List.generate(
        224,
        (y) => List.generate(
          224,
          (x) {
            final base = (y * 224 + x) * 3;
            return [
              flat[base],
              flat[base + 1],
              flat[base + 2],
            ];
          },
        ),
      ),
    );
    return cube;
  }

  List<int> _topKIndices(List<double> values, int k) {
    final indexed = List.generate(values.length, (i) => (i, values[i]));
    indexed.sort((a, b) => b.$2.compareTo(a.$2));
    return indexed.take(k).map((e) => e.$1).toList();
  }

  double _softmaxScore(List<double> logits, int index) {
    final maxLogit = logits.reduce(math.max);
    var sum = 0.0;
    for (final v in logits) {
      sum += math.exp(v - maxLogit);
    }
    return math.exp(logits[index] - maxLogit) / sum;
  }
}

