#!/usr/bin/env python3
"""Write STATUS.md from a test report and a feature-flag snapshot.

Missing input is written as unknown. This script does not invent a pass rate
or a flag value.
"""

from __future__ import annotations

import argparse
import json
import sys
import tempfile
from pathlib import Path


def load_json(path: Path | None) -> dict | None:
    if path is None:
        return None
    if not path.is_file():
        return None
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise SystemExit(f"{path} must be a JSON object")
    return data


def render(tests: dict | None, flags: dict | None) -> str:
    lines = [
        "# Status",
        "",
        "Generated by scripts/docs/gen_status.py. A missing input is unknown.",
        "",
        "## Tests",
        "",
    ]
    if tests is None:
        lines.append("- Result: unknown")
    else:
        passed = tests.get("passed")
        failed = tests.get("failed")
        if not isinstance(passed, int) or not isinstance(failed, int):
            lines.append("- Result: unknown")
        else:
            lines.append(f"- Passed: {passed}")
            lines.append(f"- Failed: {failed}")
    lines.extend(["", "## Feature flags", ""])
    if flags is None:
        lines.append("- Flags: unknown")
    else:
        values = flags.get("flags")
        if not isinstance(values, dict) or not values:
            lines.append("- Flags: unknown")
        else:
            for key in sorted(values):
                value = values[key]
                if not isinstance(value, bool):
                    lines.append(f"- `{key}`: unknown")
                else:
                    lines.append(f"- `{key}`: {'on' if value else 'off'}")
    lines.append("")
    return "\n".join(lines)


def self_test() -> int:
    missing = render(None, None)
    if "unknown" not in missing or "Passed:" in missing:
        print("missing input should stay unknown", file=sys.stderr)
        return 1
    present = render({"passed": 2, "failed": 1}, {"flags": {"polie": False}})
    if "Passed: 2" not in present or "`polie`: off" not in present:
        print("fixture values missing", file=sys.stderr)
        return 1
    if "unknown" in present.split("## Feature flags")[0].split("Passed:")[-1]:
        return 1
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "STATUS.md"
        path.write_text(render(None, None), encoding="utf-8")
        if "Result: unknown" not in path.read_text(encoding="utf-8"):
            return 1
    print("status self-test passed")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--tests", type=Path)
    parser.add_argument("--flags", type=Path)
    parser.add_argument("--out", type=Path, default=Path("STATUS.md"))
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    if args.self_test:
        return self_test()
    text = render(load_json(args.tests), load_json(args.flags))
    args.out.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
